import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {ethers} from 'ethers';
import worker from './worker.mjs';
import {STREAM_JOB,streamBatch,streamSimDelta,verifyStreamReceipt,streamOpportunityTick} from './stream-opportunity.mjs';
import {SMART_ACCOUNT} from './shop.mjs';
const fixture=JSON.parse(await fs.readFile(new URL('./docs/research/stream-evidence-2026-09-05.json',import.meta.url),'utf8'));
assert.equal(streamSimDelta(fixture.positive.result).delta,24654n);
assert.equal(streamSimDelta(fixture.negativeControl.result).ok,false);
assert.throws(()=>streamSimDelta({}),/complete/);
assert.throws(()=>streamBatch(0n,1n),/bounds/);
assert.throws(()=>streamBatch(BigInt(STREAM_JOB.maxRewardUnits)+1n,1n),/bounds/);
const I=new ethers.Interface(['event ExecutionSuccess(bytes32 txHash,uint256 payment)','event Transfer(address indexed from,address indexed to,uint256 value)']);
const hash=ethers.id('this action'),other=ethers.id('another action');
const log=(address,event,args)=>({address,...I.encodeEventLog(I.getEvent(event),args)});
const receipt={status:'0x1',transactionHash:ethers.id('transaction'),blockNumber:'0x1',logs:[log(SMART_ACCOUNT,'ExecutionSuccess',[hash,0]),log(STREAM_JOB.usdc,'Transfer',[STREAM_JOB.router,SMART_ACCOUNT,24654])]};
assert.equal(verifyStreamReceipt(receipt,hash).usdc,'0.024654');
assert.equal(verifyStreamReceipt(receipt,other).ok,false);
assert.equal(verifyStreamReceipt({...receipt,status:'0x0'},hash).ok,false);
assert.equal(verifyStreamReceipt({...receipt,logs:receipt.logs.slice(0,1)},hash).ok,false);
assert.equal(verifyStreamReceipt({...receipt,logs:[receipt.logs[0],log(STREAM_JOB.underlying,'Transfer',[STREAM_JOB.router,SMART_ACCOUNT,24654])]},hash).ok,false);
assert.equal(verifyStreamReceipt({...receipt,logs:[...receipt.logs,log(STREAM_JOB.usdc,'Transfer',[SMART_ACCOUNT,STREAM_JOB.router,24654])]},hash).ok,false);
const memory=new Map([[STREAM_JOB.key,{phase:'settled',proof:{usdc:'0.024654'}}]]);
const env={KV:{get:async k=>memory.get(k)||null,put:async(k,v)=>memory.set(k,JSON.parse(v))}};
const noRpc=async()=>{throw new Error('terminal job must not call RPC');};
assert.equal((await streamOpportunityTick(env,noRpc)).phase,'settled');
const response=await worker.fetch(new Request('https://zero-agent.broke2builtai.com/stream-opportunity'),env,{});
assert.equal(response.status,200);
assert.equal((await response.json()).state.phase,'settled');
memory.set(STREAM_JOB.key,{phase:'submitting'});
assert.equal((await streamOpportunityTick(env,noRpc)).phase,'attention');
assert.equal((await streamOpportunityTick(env,noRpc)).reserveChain,'arbitrum');
memory.set('research:surfaces',{'keeper-registries':{scans:1,contracts:1,settledUsd:0,txHashes:[]}});
const earnerResponse=await worker.fetch(new Request('https://zero-agent.broke2builtai.com/earners'),env,{});
const earner=await earnerResponse.json();
assert.equal(earner.unexamined_surfaces,7);
assert.equal(earner.surface_to_grind.surface.id,'liquidation-dust');
console.log('Stream opportunity checks passed: actual simulation fixtures, receipt binding, terminal/ambiguous states, public endpoint, persisted surface rotation.');
